"""접수함 폴더의 원문을 모두 읽어 하자대장.csv로 저장한다.

흐름: 원문 읽기(코드) → 접수 정리(AI) → 번호, 기한, 보증 판정(코드) → CSV 저장
"""
import csv
import re
import sys
from pathlib import Path

import ai
import rules

BASE = Path(__file__).parent
입력_폴더 = BASE / "data" / "접수함"
출력_파일 = BASE / "data" / "하자대장.csv"

대장_칸 = ["접수번호", "접수일", "원문파일", "위치", "공종", "하자내용", "긴급도", "조치기한",
          "공사번호", "시공업체", "준공일", "보증만료일", "보증판정", "책임구분", "상태", "비고"]

공종_목록 = {"방수", "타일", "전기", "설비", "기계", "도장", "바닥재"}


def _파일명_날짜(파일명: str) -> str | None:
    """01_20261102_B1푸드코트_누수.txt → 2026-11-02"""
    m = re.match(r"\d+_(\d{4})(\d{2})(\d{2})_", 파일명)
    return f"{m.group(1)}-{m.group(2)}-{m.group(3)}" if m else None


def _검사(정리: dict) -> list[str]:
    """AI 답에서 코드가 확인할 수 있는 문제를 모아 돌려준다."""
    문제 = []
    if len(정리["하자내용"]) > 40:
        문제.append(f"하자내용 {len(정리['하자내용'])}자(40자 초과)")
    공종들 = [c.strip() for c in 정리["공종"].split("/")]
    if 정리["공종"] != "확인필요" and not all(c in 공종_목록 for c in 공종들):
        문제.append(f"알 수 없는 공종 '{정리['공종']}'")
    if 정리["긴급도"] not in rules.기한_일수:
        문제.append(f"알 수 없는 긴급도 '{정리['긴급도']}'")
    return 문제


def 처리_상세(진행=print) -> list[dict]:
    """건마다 단계별 결과(원문, AI 정리, 코드 판정, 대장 한 행)를 돌려준다. 화면에서 과정을 보여 줄 때 쓴다."""
    파일들 = sorted(입력_폴더.glob("*.txt"))
    if not 파일들:
        raise SystemExit(f"{입력_폴더}에 접수 파일이 없습니다.")

    건들 = []
    for 파일 in 파일들:
        진행(f"[{파일.name}] AI 정리 중...")
        원문 = 파일.read_text(encoding="utf-8")
        정리 = ai.접수정리(원문)
        파일_날짜 = _파일명_날짜(파일.name)
        접수일 = 정리["접수일"] or 파일_날짜  # 원문 날짜 우선, 없으면 파일명 날짜
        if not 접수일:
            raise SystemExit(f"{파일.name}: 원문에도 파일명에도 날짜가 없습니다.")
        경고 = _검사(정리)
        if 정리["접수일"] and 파일_날짜 and 정리["접수일"] != 파일_날짜:
            경고.append(f"원문 날짜({정리['접수일']})와 파일명 날짜({파일_날짜})가 다름")
        건들.append({"파일": 파일.name, "원문": 원문, "정리": 정리, "접수일": 접수일, "경고": 경고})

    # 접수일 순, 같은 날이면 파일 이름 순으로 번호를 매긴다.
    건들.sort(key=lambda 건: (건["접수일"], 건["파일"]))
    번호들 = rules.접수번호_부여([건["접수일"] for 건 in 건들])

    행들 = []
    for 번호, 건 in zip(번호들, 건들):
        정리 = 건["정리"]
        판정 = rules.보증판정(건["접수일"], 정리["위치"], 정리["공종"])
        비고 = [칸 for 칸 in [판정["비고"], *건["경고"]] if 칸]
        행 = {
            "접수번호": 번호,
            "접수일": 건["접수일"],
            "원문파일": 건["파일"],
            "위치": 정리["위치"],
            "공종": 정리["공종"],
            "하자내용": 정리["하자내용"],
            "긴급도": 정리["긴급도"],
            "조치기한": rules.조치기한(건["접수일"], 정리["긴급도"]),
            "공사번호": 판정["공사번호"],
            "시공업체": 판정["시공업체"],
            "준공일": 판정["준공일"],
            "보증만료일": 판정["보증만료일"],
            "보증판정": 판정["보증판정"],
            "책임구분": 판정["책임구분"],
            "상태": 판정["상태"],
            "비고": " / ".join(비고),
        }
        행들.append({"원문": 건["원문"], "정리": 정리, "경고": 건["경고"], "판정": 판정, "행": 행})
    return 행들


def 처리() -> list[dict]:
    """대장에 저장할 행만 돌려준다."""
    return [건["행"] for 건 in 처리_상세()]


def 저장(행들: list[dict]) -> None:
    # utf-8-sig: 엑셀에서 열어도 한글이 깨지지 않는다.
    with open(출력_파일, "w", encoding="utf-8-sig", newline="") as f:
        쓰는이 = csv.DictWriter(f, fieldnames=대장_칸)
        쓰는이.writeheader()
        쓰는이.writerows(행들)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    행들 = 처리()
    저장(행들)
    print(f"\n{len(행들)}건을 {출력_파일}에 저장했습니다.")
    for 행 in 행들:
        print(f"{행['접수번호']}  {행['위치']}  {행['공종']}  {행['긴급도']}  {행['조치기한']}  "
              f"{행['보증판정']}/{행['책임구분']}  {행['비고']}")
