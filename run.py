"""접수를 모두 읽어 하자대장 DB에 저장한다. 입력은 두 곳이다.
- 접수함 폴더의 원문 파일
- DB 접수 테이블의 미처리 접수 (접수 화면 intake.py에서 들어온 것). 발견일을 접수일로 쓰고, 처리하면 처리완료로 바꾼다.

흐름: 원문 읽기(코드) → 접수 정리(AI) → 번호, 기한, 보증 판정(코드) → DB 저장
"""
import re
import sys
from pathlib import Path

import ai
import db
import rules

BASE = Path(__file__).parent
입력_폴더 = BASE / "data" / "접수함"
대장_칸 = db.대장_칸

공종_목록 = {"방수", "타일", "전기", "설비", "기계", "도장", "바닥재"}


def _파일명_날짜(파일명: str) -> str | None:
    """01_20261102_B1푸드코트_누수.txt → 2026-11-02"""
    m = re.match(r"\d+_(\d{4})(\d{2})(\d{2})_", 파일명)
    return f"{m.group(1)}-{m.group(2)}-{m.group(3)}" if m else None


def _검사(정리: dict) -> list[str]:
    """AI 답에서 코드가 확인할 수 있는 문제를 모아 돌려준다."""
    문제 = []
    if len(정리["하자내용"]) > 40:
        문제.append(f"하자내용 {len(정리['하자내용'])}자(40자 초과)")
    공종들 = [c.strip() for c in 정리["공종"].split("/")]
    if 정리["공종"] != "확인필요" and not all(c in 공종_목록 for c in 공종들):
        문제.append(f"알 수 없는 공종 '{정리['공종']}'")
    if 정리["긴급도"] not in rules.기한_일수:
        문제.append(f"알 수 없는 긴급도 '{정리['긴급도']}'")
    return 문제


DB접수_접두 = "DB접수-"  # 원문파일 칸에 적는 이름. 예) DB접수-12


def _접수_원문(건: dict) -> str:
    """DB 접수 한 건을 AI에게 줄 원문 글로 만든다."""
    return (f"[접수 화면] 발견일: {건['발견일']}\n"
            f"접수자: {건['접수자']} ({건['부서']})\n"
            f"위치: {건['위치']}\n\n{건['내용']}")


def 접수_모으기() -> list[dict]:
    """처리할 접수를 모은다: 접수함 폴더의 파일 + DB의 미처리 접수.

    날짜_우선: True면 기준_날짜(발견일)를 접수일로 쓴다. 파일은 원문 날짜가 우선이다.
    """
    항목들 = []
    for 파일 in sorted(입력_폴더.glob("*.txt")):
        항목들.append({"원문파일": 파일.name, "원문": 파일.read_text(encoding="utf-8"),
                    "기준_날짜": _파일명_날짜(파일.name), "기준_이름": "파일명 날짜", "날짜_우선": False})
    for 건 in db.접수_미처리_읽기():
        항목들.append({"원문파일": f"{DB접수_접두}{건['id']}", "원문": _접수_원문(건),
                    "기준_날짜": 건["발견일"], "기준_이름": "발견일", "날짜_우선": True})
    return 항목들


def 처리_상세(진행=print) -> list[dict]:
    """건마다 단계별 결과(원문, AI 정리, 코드 판정, 대장 한 행)를 돌려준다. 화면에서 과정을 보여 줄 때 쓴다."""
    항목들 = 접수_모으기()
    if not 항목들:
        raise RuntimeError(f"처리할 접수가 없습니다. ({입력_폴더}에 파일이 없고, DB에 미처리 접수도 없습니다.)")

    건들 = []
    for 항목 in 항목들:
        진행(f"[{항목['원문파일']}] AI 정리 중...")
        정리 = ai.접수정리(항목["원문"])
        기준 = 항목["기준_날짜"]
        if 항목["날짜_우선"] and 기준:
            접수일 = 기준  # DB 접수는 발견일이 접수일이다
        else:
            접수일 = 정리["접수일"] or 기준  # 파일은 원문 날짜 우선, 없으면 파일명 날짜
        if not 접수일:
            raise RuntimeError(f"{항목['원문파일']}: 날짜를 알 수 없습니다. (원문, {항목['기준_이름']} 모두 없음)")
        경고 = _검사(정리)
        if 정리["접수일"] and 기준 and 정리["접수일"] != 기준:
            경고.append(f"원문 날짜({정리['접수일']})와 {항목['기준_이름']}({기준})가 다름")
        건들.append({"파일": 항목["원문파일"], "원문": 항목["원문"], "정리": 정리, "접수일": 접수일, "경고": 경고})

    # 접수일 순, 같은 날이면 원문파일 이름 순으로 번호를 매긴다.
    # 이미 대장에 있는 번호(이번에 다시 처리하는 건 제외)는 건너뛴다. 다른 건을 덮어쓰지 않기 위해서다.
    건들.sort(key=lambda 건: (건["접수일"], 건["파일"]))
    이번_원문파일 = {건["파일"] for 건 in 건들}
    사용중 = {행["접수번호"] for 행 in db.대장_읽기() if 행["원문파일"] not in 이번_원문파일}
    번호들 = rules.접수번호_부여([건["접수일"] for 건 in 건들], 사용중)

    행들 = []
    for 번호, 건 in zip(번호들, 건들):
        정리 = 건["정리"]
        판정 = rules.보증판정(건["접수일"], 정리["위치"], 정리["공종"])
        비고 = [칸 for 칸 in [판정["비고"], *건["경고"]] if 칸]
        행 = {
            "접수번호": 번호,
            "접수일": 건["접수일"],
            "원문파일": 건["파일"],
            "위치": 정리["위치"],
            "공종": 정리["공종"],
            "하자내용": 정리["하자내용"],
            "긴급도": 정리["긴급도"],
            "조치기한": rules.조치기한(건["접수일"], 정리["긴급도"]),
            "공사번호": 판정["공사번호"],
            "시공업체": 판정["시공업체"],
            "준공일": 판정["준공일"],
            "보증만료일": 판정["보증만료일"],
            "보증판정": 판정["보증판정"],
            "책임구분": 판정["책임구분"],
            "상태": 판정["상태"],
            "비고": " / ".join(비고),
        }
        행들.append({"원문": 건["원문"], "정리": 정리, "경고": 건["경고"], "판정": 판정, "행": 행})
    return 행들


def 처리() -> list[dict]:
    """대장에 저장할 행만 돌려준다."""
    return [건["행"] for 건 in 처리_상세()]


def 저장(행들: list[dict]) -> None:
    """하자대장 DB에 넣는다. 같은 접수번호는 덮어쓴다. DB 접수에서 온 건은 처리완료로 바꾼다."""
    db.대장_저장(행들)
    for 행 in 행들:
        if 행["원문파일"].startswith(DB접수_접두):
            db.접수_처리완료(int(행["원문파일"][len(DB접수_접두):]), 행["접수번호"])


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    try:
        행들 = 처리()
    except RuntimeError as e:
        sys.exit(str(e))
    저장(행들)
    print(f"\n{len(행들)}건을 하자대장 DB에 저장했습니다.")
    for 행 in 행들:
        print(f"{행['접수번호']}  {행['위치']}  {행['공종']}  {행['긴급도']}  {행['조치기한']}  "
              f"{행['보증판정']}/{행['책임구분']}  {행['비고']}")
